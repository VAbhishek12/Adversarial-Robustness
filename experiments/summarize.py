"""Writes results/SUMMARY.md: one table with every finished network."""
import json, os

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
J = lambda n: json.load(open(os.path.join(R, n))) if os.path.exists(os.path.join(R, n)) else {}
ev, me = J("new_eval.json"), J("metrics.json")
f = lambda v, d=1: "n/a" if v is None or v != v else f"{v:.{d}f}"

lines = ["# Results summary (auto-generated by experiments/summarize.py)", "",
         "Accuracy in %, pixel space, eps in 1/255. PGD-20 on 10 000 test images. APGD is the worst case of APGD-CE and "
         "APGD-DLR on the first 1 000 test images at 8/255 (n/a: not measured for that network).", "",
         "| Network | Clean | PGD-20 8/255 | APGD 8/255 | Last-epoch PGD-20 8/255 | Params (M) | Train min |",
         "|---|---|---|---|---|---|---|"]
for n in ["r18_plain", "r18_full", "r18_nodenoise", "r18_noblur", "r18v2_plain"]:
    if n not in ev:
        continue
    r, tr = ev[n], J(f"train_{n}.json")
    mins = tr["log"][-1]["minutes"] if tr and tr.get("log") else None
    lines.append(f"| {n} | {f(r['clean'], 2)} | {f(r['pgd20_8_full'], 2)} | {f(r.get('autoattack_8'))} | "
                 f"{f(r.get('final', {}).get('pgd20_8'))} | {f(r.get('params_M'), 2)} | {f(mins, 0)} |")

lines += ["", "## Full metric suite (clean on all 10 000 test images, attacked on the first 2 000)", "",
          "| Network | Clean acc | Clean P (macro) | Clean R (macro) | Clean F1 | MCC | AUROC | ECE % | PGD-20 8/255 acc | PGD-20 F1 | ASR 8/255 % | Mean critical eps (/255) |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for n, r in me.items():
    c, a = r["clean"], r["adv"]["8"]
    lines.append(f"| {n} | {c['accuracy']:.2f} | {c['precision_macro']:.2f} | {c['recall_macro']:.2f} | {c['f1_macro']:.2f} | {c['mcc']:.3f} | "
                 f"{c['auroc_macro']:.3f} | {c['ece']:.1f} | {a['accuracy']:.2f} | {a['f1_macro']:.2f} | {r['asr']['8']:.1f} | "
                 f"{r['critical_eps']['mean']:.2f} |")
open(os.path.join(R, "SUMMARY.md"), "w", encoding="utf8").write("\n".join(lines) + "\n")
print("summary written")
